"""Vendor a pinned, local SimulationCraft checkout. No network or code execution.

The original APL text is preserved. This does NOT flatten lists, remove conditions,
translate unsupported expressions to false, or claim live rotation compatibility.
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIN = "faf366dbb9e60c9bab904d5c91da8adaad10ab85"
CLASSES = {
    "WARRIOR": 1, "PALADIN": 2, "HUNTER": 3, "ROGUE": 4, "PRIEST": 5,
    "DEATH_KNIGHT": 6, "SHAMAN": 7, "MAGE": 8, "WARLOCK": 9, "MONK": 10,
    "DRUID": 11, "DEMON_HUNTER": 12, "EVOKER": 13,
}


def slug(name):
    return re.sub(r"[^a-z0-9_]", "", name.lower().replace(" ", "_"))


def lua_string(value):
    # These strings are data, never evaluated as Lua.
    return json.dumps(value, ensure_ascii=False)


def long_string(value):
    eq = "="
    while "]" + eq + "]" in value:
        eq += "="
    # Lua discards the first newline after a long-string opener. Supply a sentinel
    # so an upstream leading newline survives, including in provenance hashes.
    return "[" + eq + "[\n" + value + "]" + eq + "]"


def generate(source):
    head = subprocess.check_output(
        ["git", "-C", str(source), "rev-parse", "HEAD"], text=True
    ).strip()
    if head != PIN:
        raise ValueError(f"Expected audited commit {PIN}; received {head}")
    generated = source / "engine/dbc/generated"
    raw_specs = (generated / "sc_specialization_data.inc").read_text(encoding="utf-8")
    spell_path = generated / "sc_spell_data.inc"
    spell_text = spell_path.read_text(encoding="utf-8")
    build = re.search(r"wow build level ([\d.]+)", spell_text).group(1)
    rows, needed, manifest = [], set(), []
    for name, number in re.findall(r"^\s*([A-Z_]+)\s*=\s*(\d+)", raw_specs, re.M):
        class_name = next((c for c in CLASSES if name.startswith(c + "_")), None)
        if not class_name:
            continue
        spec = name[len(class_name) + 1:].lower()
        key = class_name.lower().replace("_", "") + "_" + spec
        rel = f"ActionPriorityLists/default/{key}.simc"
        path = source / rel
        raw = path.read_text(encoding="utf-8") if path.exists() else ""
        for match in re.finditer(r"actions(?:\.\w+)?\+?=\s*/?([a-z0-9_]+)", raw):
            needed.add(match.group(1))
        for match in re.finditer(r"\b(?:buff|debuff|dot|cooldown|talent|action)\.([a-z0-9_]+)", raw):
            needed.add(match.group(1))
        rows.append(
            f'P.specs[{number}]={{id={number},classID={CLASSES[class_name]},'
            f'class={lua_string(class_name.replace("_", ""))},'
            f'key={lua_string(key)},name={lua_string(name.replace("_", " ").title())},'
            f'source={lua_string(rel if raw else "")},raw={long_string(raw)}}}\n'
        )
        manifest.append({
            "specID": int(number), "key": key, "source": rel if raw else None,
            "sha256": hashlib.sha256(raw.encode()).hexdigest() if raw else None,
            "status": "unverified_source" if raw else "no_upstream_apl",
        })
    candidates = {}
    for name, sid in re.findall(r'^\s*\{\s*"([^"]+)"\s*,\s*(\d+)', spell_text, re.M):
        token = slug(name)
        if token in needed:
            candidates.setdefault(token, set()).add(int(sid))
    lua = (
        "-- Generated by tools/sync_simc.py. SimulationCraft data: GPL-3.0-or-later.\n"
        "-- Original rules retained; unknown inputs must never be treated as false.\n"
        "local _, A = ...\nlocal P = {specs={},spells={}}\nA.Packs=P\n"
        f"P.commit={lua_string(head)}\nP.build={lua_string(build)}\n"
        'P.repository="https://github.com/simulationcraft/simc"\n'
        + "".join(rows)
    )
    for token, ids in sorted(candidates.items()):
        lua += f"P.spells[{lua_string(token)}]={{" + ",".join(map(str, sorted(ids))) + "}\n"
    (ROOT / "Packs").mkdir(exist_ok=True)
    (ROOT / "Packs/Generated.lua").write_text(lua, encoding="utf-8", newline="\n")
    (ROOT / "Packs/manifest.json").write_text(json.dumps(
        {"commit": head, "build": build, "license": "GPL-3.0-or-later",
         "specs": manifest, "tokens": len(candidates)}, ensure_ascii=False, indent=2
    ) + "\n", encoding="utf-8")
    shutil.copyfile(source / "COPYING", ROOT / "LICENSE")
    print(f"{len(rows)} specs / {sum(bool(x['source']) for x in manifest)} APLs / "
          f"{len(candidates)} spell tokens / build {build}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout", type=Path)
    generate(parser.parse_args().checkout)
